# Generates eva_assets.h (fonts + bitmaps) from the approved HTML prototype data.
import re, json, sys
html = open(r'C:/Users/Gabriel/Projects/eva-oled-proposta.html', encoding='utf-8').read()
out = sys.argv[1]

def js_obj(name):
    m = re.search(r'const ' + name + r'=\{(.*?)\};', html, re.S)
    body = m.group(1)
    d = {}
    for k, v in re.findall(r'(?:"([^"]+)"|(\w)):"([^"]*)"', body) and [(a or b, c) for a, b, c in re.findall(r'(?:"([^"]+)"|(\w)):"([^"]*)"', body)]:
        d[k] = v
    return d

F3 = js_obj('F3')
# F5 needs the JS fix-ups applied
F5 = {}
m = re.search(r'const F5=\{(.*?)\};', html, re.S).group(1)
for a, b, v, tail in re.findall(r'(?:"([^"]+)"|(\w)):"([^"]*)"((?:\.replace\([^)]*\))?(?: \+ "[^"]*")?)', m):
    k = a or b
    if '+ "' in tail:
        v += re.search(r'\+ "([^"]*)"', tail).group(1)
    v = v.replace(' ', '')
    F5[k] = v
F5['C'] = '0E11101010110E'
F5['D'] = '1C12111111121C'
for k, v in F5.items():
    assert len(v) == 14, (k, v)
for k, v in F3.items():
    assert len(v) == 5, (k, v)

def arr(name):
    m = re.search(r'const ' + name + r'=(\[.*?\]);', html, re.S)
    return json.loads(m.group(1))
LEAF = arr('LEAF'); LEAF22 = arr('LEAF22')
SERIF = {}
sm = re.search(r'const SERIF=\{(.*?)\};', html, re.S).group(1)
for k, v in re.findall(r'(\w):(\[[^\]]*\])', sm):
    SERIF[k] = json.loads(v)

def bitrows(rows):
    w = len(rows[0]); assert w <= 32
    return w, len(rows), [sum(1 << (w - 1 - i) for i, c in enumerate(r) if c == '#') for r in rows]

L = ['/* Generated by gen_assets.py from the approved prototype - do not edit by hand */', '#pragma once', '#include <stdint.h>', '']
# 3x5 font, ASCII 32..95
L.append('/* 3x5 font: 5 rows, bit2 = left column */')
L.append('static const uint8_t EVA_F3[64][5] = {')
for c in range(32, 96):
    g = F3.get(chr(c), '00000')
    L.append('    {%s}, /* %r */' % (', '.join(g), chr(c)))
L.append('};')
L.append('/* 5x7 font: 7 rows, bit4 = left column */')
L.append('static const uint8_t EVA_F5[64][7] = {')
for c in range(32, 96):
    g = F5.get(chr(c), '00000000000000')
    L.append('    {%s}, /* %r */' % (', '.join('0x' + g[i:i + 2] for i in range(0, 14, 2)), chr(c)))
L.append('};')
for name, rows in (('LEAF', LEAF), ('LEAF22', LEAF22)):
    w, h, bits = bitrows(rows)
    L.append(f'#define EVA_{name}_W {w}')
    L.append(f'#define EVA_{name}_H {h}')
    L.append(f'static const uint32_t EVA_{name}[{h}] = {{' + ', '.join(hex(b) for b in bits) + '};')
L.append('/* serif glyphs for the NERV logo, 9 rows, MSB = left */')
for k in 'NERV':
    w, h, bits = bitrows(SERIF[k])
    L.append(f'static const uint8_t EVA_SERIF_{k}[9] = {{' + ', '.join(hex(b) for b in bits) + f'}}; /* width {w} */')
    L.append(f'#define EVA_SERIF_{k}_W {w}')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
print('ok', len(F3), len(F5), len(LEAF), len(LEAF22))
